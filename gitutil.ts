/**
 * Every object reachable from `roots`: commit -> tree + parents, tree -> entries
 * (gitlinks skipped), tag -> its target, blob -> nothing. With `stopAt`, a commit
 * in that set is included with its tree and blobs, but its parents are not
 * traversed (a shallow boundary's parents are not held).
 */
export function collectReachable(
  roots: Iterable<string>,
  lookup: (oid: string) => GitObject | undefined,
  options: { stopAt?: ReadonlySet<string>; allowMissing?: boolean } = {},
): Set<string> {
  const seen = new Set<string>();
  const queue: string[] = [];
  for (const root of roots) if (isObjectId(root)) queue.push(root);
  while (queue.length) {
    const oid = queue.pop()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (!object) {
      if (options.allowMissing) continue;
      throw new Error(`object ${oid} is missing from the store`);
    }
    seen.add(oid);
    if (object.type === 'commit') {
      const commit = parseCommit(object.data);
      queue.push(commit.tree);
      if (options.stopAt?.has(oid)) continue;
      for (const parent of commit.parents) queue.push(parent);
    } else if (object.type === 'tag') {
      queue.push(parseTag(object.data).object);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push(entry.oid);
      }
    }
  }
  return seen;
}

/** The distance (generations) from the nearest want, for commits; -1 when unreachable. */
export function commitDistances(
  wants: readonly string[],
  lookup: (oid: string) => GitObject | undefined,
): Map<string, number> {
  const dist = new Map<string, number>();
  const queue: string[] = [];
  for (const want of wants) {
    const object = lookup(want);
    if (!object) continue;
    if (object.type === 'commit') {
      if (!dist.has(want)) {
        dist.set(want, 0);
        queue.push(want);
      }
    } else if (object.type === 'tag') {
      const target = parseTag(object.data).object;
      const targetObj = lookup(target);
      if (targetObj?.type === 'commit' && !dist.has(target)) {
        dist.set(target, 0);
        queue.push(target);
      }
    }
  }
  let head = 0;
  while (head < queue.length) {
    const oid = queue[head++]!;
    const d = dist.get(oid)!;
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) {
      if (!dist.has(parent) && lookup(parent)?.type === 'commit') {
        dist.set(parent, d + 1);
        queue.push(parent);
      }
    }
  }
  return dist;
}

/** True when `ancestor` is `commit` itself or one of its ancestors. */
export function isAncestor(
  ancestor: string,
  commit: string,
  lookup: (oid: string) => GitObject | undefined,
): boolean {
  if (ancestor === commit) return true;
  const seen = new Set<string>();
  const queue: string[] = [commit];
  while (queue.length) {
    const oid = queue.pop()!;
    if (oid === ancestor) return true;
    if (seen.has(oid)) continue;
    seen.add(oid);
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) queue.push(parent);
  }
  return false;
}
